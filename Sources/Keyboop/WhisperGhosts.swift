import Foundation

/// Фразы-призраки Whisper: обрывки титров из обучающих данных, которые модель выдаёт на тишине,
/// шуме и обрезанных хвостах.
///
/// Проблема известная и не наша: Whisper учили в том числе на субтитрах с ютуба, и в отсутствие
/// разборчивой речи он «дописывает» самое вероятное продолжение такого текста — подпись
/// переводчика, просьбу подписаться, «продолжение следует». Отчёт #48: «Субтитры сделал DimaTorzok
/// → вот это постоянно выдаёт». автор 30.07: собрать список и не пускать их наружу.
///
/// ⚠️ ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА: удалить чужое слово хуже, чем пропустить призрак.
/// Поэтому шаблоны срабатывают, только когда фраза стоит ЦЕЛИКОМ отдельным предложением: либо она
/// и есть весь результат, либо это законченное предложение в начале или конце. Внутри живой фразы
/// мы не вырезаем ничего и никогда — «спасибо за просмотр» человек может сказать и всерьёз.
enum WhisperGhosts {

    /// Шаблоны целых предложений. Регистр не важен, знаки препинания по краям не важны.
    /// Имена в титрах разные («DimaTorzok», «А. Синецкая»), поэтому хвост шаблона свободный.
    private static let patterns: [String] = [
        // Русские титры и призывы.
        // ⚠️ У «субтитров» ОБЯЗАТЕЛЕН глагол авторства: шаблон `^субтитр\w*` без него убивал живую
        // фразу «Субтитры к фильму мы сделаем сами» (поймано тестом до релиза). Список глаголов
        // расширять можно, а до «любого продолжения» ослаблять нельзя.
        #"^субтитры (создал|создавал|сделал|делал|подготовил|подготовлены|предоставлены|by)\b.*$"#,
        #"^редактор субтитров\b.*$"#,
        // ⚠️ Ниже шаблоны БЕЗ «любого продолжения»: фраза должна быть предложением целиком.
        // «Продолжение следует за вступлением, так устроена книга» — живая речь, и с хвостом `.*`
        // она стиралась (поймано тестом). Знаки в конце снимает нормализация, поэтому «…» не мешает.
        #"^продолжение следует$"#,
        #"^спасибо за просмотр$"#,
        #"^спасибо за внимание$"#,
        #"^подписывайтесь на канал$"#,
        #"^подписывайся на канал$"#,
        #"^ставьте лайк$"#,
        #"^не забудьте подписаться$"#,
        // Английские, приезжают даже на русской речи
        #"^thanks? (you )?for watching$"#,
        #"^subtitles by\b.*$"#,
        #"^subtitles? and translation by\b.*$"#,
        #"^please subscribe$"#,
        #"^amara\.org\b.*$"#,
        #"^www\.[a-z0-9.-]+$"#,
    ]

    private static let regexes: [NSRegularExpression] = patterns.compactMap {
        try? NSRegularExpression(pattern: $0, options: [.caseInsensitive])
    }

    /// Убрать призраки. Возвращает очищенный текст (может стать пустым — значит, речи не было вовсе).
    static func clean(_ text: String) -> String {
        let sentences = split(text)
        guard !sentences.isEmpty else { return text }
        var kept = sentences
        // Срезаем ТОЛЬКО с краёв и пока срезается: призрак почти всегда приклеен спереди или сзади,
        // а вырезание из середины разорвало бы живую фразу пополам.
        while let first = kept.first, isGhost(first) { kept.removeFirst() }
        while let last = kept.last, isGhost(last) { kept.removeLast() }
        // Огрызки из одних знаков после срезки оставлять нельзя: «Продолжение следует...» давало
        // в остатке « . . », и это уезжало в поле как настоящий текст.
        kept = kept.filter { $0.rangeOfCharacter(from: .alphanumerics) != nil }
        guard kept.count != sentences.count else { return text }
        let removed = sentences.count - kept.count
        // В лог — только СКОЛЬКО убрали, без содержимого: принцип №2 запрещает писать распознанное.
        kbLog("whisper: убрано фраз-призраков: \(removed)")
        return kept.joined(separator: " ").trimmingCharacters(in: .whitespacesAndNewlines)
    }

    /// Разбить на предложения. Граница — знак конца плюс ПРОБЕЛ после него.
    ///
    /// ⚠️ Пробел обязателен, и вот почему (поймано тестом): резать по каждой точке значит рвать
    /// «А.Синецкая» на «А.» и «Синецкая», а «Продолжение следует...» — на фразу и два огрызка «.».
    /// В первом случае половина титров оставалась в тексте, во втором в поле уезжали голые точки.
    private static func split(_ text: String) -> [String] {
        let parts = text.components(separatedBy: .newlines).flatMap { line -> [String] in
            line.replacingOccurrences(of: #"([.!?…]+)\s+"#, with: "$1\u{1}", options: .regularExpression)
                .components(separatedBy: "\u{1}")
        }
        return parts.map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }.filter { !$0.isEmpty }
    }

    private static func isGhost(_ sentence: String) -> Bool {
        // Нормализуем: убираем знаки по краям и схлопываем пробелы, иначе «Субтитры…» с многоточием
        // и «субтитры» с точкой требовали бы отдельных шаблонов.
        let s = sentence
            .trimmingCharacters(in: CharacterSet(charactersIn: " \t\n.,!?…-–—:;\"'«»()"))
            .replacingOccurrences(of: "\\s+", with: " ", options: .regularExpression)
        guard !s.isEmpty else { return false }
        let range = NSRange(s.startIndex..., in: s)
        return regexes.contains { $0.firstMatch(in: s, options: [], range: range) != nil }
    }
}
