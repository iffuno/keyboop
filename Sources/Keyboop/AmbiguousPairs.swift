import Foundation

/// СПОРНЫЕ ПАРЫ: латинский токен и русское слово, которые набираются ОДНИМИ И ТЕМИ ЖЕ клавишами,
/// и оба существуют в своём языке («vs» ↔ «мы»). Именно здесь strict-gate (валидное слово не
/// трогаем) обязан выбрать за человека — а угадать за всех нельзя: кто-то пишет «versus» каждый
/// день, кто-то — «мы» в каждом втором предложении. Поэтому выбор отдаём пользователю.
///
/// Данные: аудит 25.07.2026 — все 156 пар посчитаны по словарям
/// приложения, решения сняты вызовом настоящего LayoutDetector. Здесь оставлены только те, где
/// ОБЕ стороны реально встречаются; пары с мусорной стороной («ab»↔«фи») не показываем.
///
/// ⚠️ Своего хранилища у страницы НЕТ и не нужно: выбор пишется в exceptions.forceSwap, который
/// детектор проверяет ДО всех встроенных списков. Одна запись даёт сразу оба поведения:
/// forceSwap∋«мы» → набранное «vs» превратится в «мы» (LayoutDetector строка ~218), а набранное
/// «мы» останется как есть (строка ~221). Меньше кода — меньше расхождений.
enum AmbiguousPairs {

    struct Pair {
        let en: String       // как выглядит на латинской раскладке
        let ru: String       // то же самое, набранное по-русски
    }

    /// Порядок — по практической пользе, а не по алфавиту: сверху то, где русское слово частотное
    /// и промах заметен каждый день, снизу — редкие случаи. Так человек находит нужное сразу.
    static let list: [Pair] = [
        Pair(en: "vs",    ru: "мы"),      // пример, с которого всё началось
        Pair(en: "here",  ru: "руку"),
        Pair(en: "herb",  ru: "руки"),
        Pair(en: "her",   ru: "рук"),
        Pair(en: "dbl",   ru: "вид"),
        Pair(en: "tt",    ru: "ее"),      // «ее» = «её» без ё
        Pair(en: "cj",    ru: "со"),
        Pair(en: "rj",    ru: "ко"),
        Pair(en: "ne",    ru: "ту"),
        Pair(en: "dj",    ru: "во"),
        Pair(en: "tim",   ru: "ешь"),
        Pair(en: "leif",  ru: "душа"),
        Pair(en: "lei",   ru: "душ"),
        Pair(en: "verb",  ru: "муки"),
        Pair(en: "inert", ru: "штуке"),
        Pair(en: "celt",  ru: "суде"),
        Pair(en: "dyer",  ru: "внук"),
        Pair(en: "buh",   ru: "игр"),
        Pair(en: "lye",   ru: "дну"),
        Pair(en: "neh",   ru: "тур"),
        Pair(en: "vlf",   ru: "мда"),
        Pair(en: "abu",   ru: "фиг"),
        // Сокращения: живые с обеих сторон.
        Pair(en: "cv",    ru: "см"),
        Pair(en: "rv",    ru: "км"),
        Pair(en: "ru",    ru: "кг"),
        Pair(en: "rd",    ru: "кв"),
        Pair(en: "vu",    ru: "мг"),
        Pair(en: "uh",    ru: "гр"),
        Pair(en: "in",    ru: "шт"),
        Pair(en: "nsc",   ru: "тыс"),
        Pair(en: "lng",   ru: "дтп"),
        Pair(en: "ids",   ru: "швы"),
        // Реже, но люди спрашивали.
        Pair(en: "tv",    ru: "ем"),
        Pair(en: "key",   ru: "лун"),
        Pair(en: "keys",  ru: "луны"),
        Pair(en: "ev",    ru: "ум"),
    ]

    /// Три состояния строки. `auto` — ДЕФОЛТ: приоритет не фиксируем, спорную пару решает обычная
    /// логика (словари + контекст фразы). Решение автора 25.07: «по умолчанию нет смысла фиксировать
    /// приоритет какого-то слова» — жёсткий выбор делает человек, если ему так удобнее.
    enum Choice { case en, auto, ru }

    /// Что выбрано СЕЙЧАС. Читаем только ЯВНЫЕ записи пользователя: если их нет — это `auto`,
    /// и тумблер честно показывает «по контексту», а не результат наших внутренних списков.
    static func choice(_ p: Pair) -> Choice {
        let forced = ExceptionStore.shared.forceSwap
        if forced.contains(p.ru) { return .ru }
        if forced.contains(p.en) { return .en }
        return .auto
    }

    /// Записать выбор. Победившая сторона идёт в forceSwap, проигравшая оттуда убирается — иначе две
    /// записи спорили бы между собой на разных ветках каскада. `auto` снимает обе: возвращаем пару
    /// под обычную логику.
    static func choose(_ p: Pair, _ choice: Choice) {
        let exc = ExceptionStore.shared
        exc.removeForceSwap(p.en)
        exc.removeForceSwap(p.ru)
        switch choice {
        case .ru:   exc.addForceSwap(p.ru)     // addForceSwap сам убирает слово из ignored
        case .en:   exc.addForceSwap(p.en)
        case .auto: break
        }
    }
}
