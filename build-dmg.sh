#!/bin/bash
# ⚠️  ЛЕГАСИ / ТОЛЬКО ДЛЯ ЛОКАЛЬНОГО ТЕСТА. Делает SELF-SIGNED DMG (без нотаризации) —
#     macOS будет ругаться «неизвестный разработчик». Для РАЗДАЧИ ПОЛЬЗОВАТЕЛЯМ и сайта
#     используй release.sh (Developer ID + нотаризация Apple → открывается без предупреждений).
#     Не путать выводы: оба пишут Keyboop.dmg в корень — этот перезапишет нотаризованный!
# Собирает Keyboop.app (self-signed) и упаковывает в Keyboop.dmg для быстрой локальной проверки.
set -e
cd "$(dirname "$0")"

echo "▸ Сборка приложения…"
bash build-app.sh

APP="Keyboop.app"
DMG="Keyboop.dmg"
VOL="Keyboop"
STAGING="dmg-staging"

rm -rf "$STAGING" "$DMG"
mkdir -p "$STAGING"
cp -R "$APP" "$STAGING/"
ln -s /Applications "$STAGING/Applications"

# Короткая памятка прямо в образе. ВНИМАНИЕ: это SELF-SIGNED тест-сборка, поэтому
# здесь (и только здесь) правый-клик→«Открыть». В нотаризованном релизе (release.sh)
# памятка другая — без обхода, приложение открывается сразу.
cat > "$STAGING/Как установить.txt" <<'TXT'
Keyboop — ЛОКАЛЬНАЯ ТЕСТ-СБОРКА (self-signed, не нотаризована)

1. Перетащи Keyboop в папку Applications (ярлык рядом).
2. Первый запуск: правый клик по Keyboop → «Открыть» → «Открыть»
   (обход предупреждения о неизвестном разработчике — у этой ТЕСТ-сборки
    самоподписанный сертификат. У релиза с keyboop.com такого нет — он
    нотаризован Apple и открывается сразу.)
3. Разреши доступ к Универсальному доступу (Accessibility), когда попросит —
   без него не работает переключение раскладки и голос. Включишь — заработает
   сразу, перезапуск не нужен.
4. Для голосового набора: Настройки → Голосовой набор → скачай модель
   (кнопка «Скачать» у нужной модели). Потом зажми правый ⌥ и говори.

Keyboop не выходит в интернет (кроме явной кнопки скачивания модели).
Вопросы — пиши.
TXT

echo "▸ Упаковка DMG…"
hdiutil create -volname "$VOL" -srcfolder "$STAGING" -ov -format UDZO "$DMG" >/dev/null
rm -rf "$STAGING"

SIZE=$(du -h "$DMG" | cut -f1)
echo "✓ Готово: $DMG ($SIZE)"
echo "  Передай друзьям. Внутри — инструкция «Как установить.txt»."
